// test-timecard-export.js — unit tests for the pure time-card TSV serializer.
// Run via `npm test`.
import assert from 'node:assert/strict';
import {
  buildTimecardText, effectiveThreshold, effectiveMultiplier
} from '../src/engine/timecard-export.js';

let pass = 0;
const t = (name, fn) => {
  fn();
  pass++;
  console.log('ok  - ' + name);
};

const TODAY = '2026-07-28';
const day = (label, start, end, breakMin) => ({ label, start, end, breakMin });

// A model with every optional block off unless the case turns it on.
const model = (over = {}) => ({
  rows: [],
  show: { otHours: false, pay: false, otPay: false },
  otOn: false,
  otThreshold: 40,
  otMult: 1.5,
  rate: NaN,
  today: TODAY,
  ...over
});

// --- 1. golden output --------------------------------------------------------
const GOLDEN_MODEL = model({
  rows: [
    day('Monday', '09:00', '17:00', '30'),
    day('Tuesday', '09:00', '17:00', '30'),
    day('Wednesday', '09:00', '17:00', '30'),
    day('Thursday', '09:00', '17:00', '30'),
    day('Friday', '09:00', '17:00', '30'),
    day('Saturday', '09:00', '17:30', '')
  ],
  show: { otHours: true, pay: true, otPay: true },
  otOn: true,
  rate: 20
});

// The rounding statement, exactly as the serializer composes it. Spelled out
// here rather than imported so a reworded sentence has to be re-approved.
const ROUND_HOURS =
  'Day hours are shown to 2 decimals, so adding that column can differ slightly '
  + 'from the totals, which come from exact minutes. The h:mm column is exact.';
const ROUND_PAY = 'Pay is rounded to the cent.';

const GOLDEN_TEXT = [
  'Day\tStart\tEnd\tBreak (min)\tHours (decimal)\tHours (h:mm)',
  'Monday\t09:00\t17:00\t30\t7.50\t7:30',
  'Tuesday\t09:00\t17:00\t30\t7.50\t7:30',
  'Wednesday\t09:00\t17:00\t30\t7.50\t7:30',
  'Thursday\t09:00\t17:00\t30\t7.50\t7:30',
  'Friday\t09:00\t17:00\t30\t7.50\t7:30',
  'Saturday\t09:00\t17:30\t0\t8.50\t8:30',
  '',
  'Total hours (decimal)\t46.00',
  'Total hours (h:mm)\t46:00',
  'Regular hours (first 40 h/week)\t40.00',
  'Overtime hours\t6.00',
  'Hourly rate (USD)\t20.00',
  'Regular pay\t800.00',
  'Overtime pay (1.5x rate)\t180.00',
  'Estimated gross pay\t980.00',
  '',
  ROUND_HOURS + ' ' + ROUND_PAY,
  'Estimate only, not an official payroll record.',
  'Generated by the Tools Berry hours calculator on 2026-07-28',
  'https://tools-berry.com/hours-calculator/'
].join('\n');

t('golden: the section 3.5 model serializes byte for byte', () =>
  assert.equal(buildTimecardText(GOLDEN_MODEL), GOLDEN_TEXT));

// --- 2. untouched row --------------------------------------------------------
t('untouched row: 6 fields, 5 tabs, both Hours cells empty', () => {
  const out = buildTimecardText(model({ rows: [day('Thursday', '', '', '')] }));
  const line = out.split('\n')[1];
  assert.equal(line, 'Thursday\t\t\t\t\t');
  assert.equal(line.split('\t').length, 6);
  assert.equal((line.match(/\t/g) || []).length, 5);
  const cells = line.split('\t');
  assert.equal(cells[4], '');
  assert.equal(cells[5], '');
});

// --- 3. break clamping -------------------------------------------------------
t('break: negative clamps to 0 when the row computes, echoes when it does not', () => {
  const computes = buildTimecardText(model({ rows: [day('Mon', '09:00', '17:00', '-30')] }));
  assert.equal(computes.split('\n')[1].split('\t')[3], '0');
  const doesNot = buildTimecardText(model({ rows: [day('Mon', '09:00', '', '-30')] }));
  assert.equal(doesNot.split('\n')[1].split('\t')[3], '-30');
});

// --- 4. overnight ------------------------------------------------------------
t('overnight: 22:00 to 06:00 annotates End and reports 8.00', () => {
  const cells = buildTimecardText(model({ rows: [day('Mon', '22:00', '06:00', '')] }))
    .split('\n')[1].split('\t');
  assert.equal(cells[2], '06:00 (+1 day)');
  assert.equal(cells[4], '8.00');
});

// --- 5. equal start and end --------------------------------------------------
t('equal times: 09:00 to 09:00 is a 24.00 h shift under the same rule', () => {
  const cells = buildTimecardText(model({ rows: [day('Mon', '09:00', '09:00', '')] }))
    .split('\n')[1].split('\t');
  assert.equal(cells[2], '09:00 (+1 day)');
  assert.equal(cells[4], '24.00');
});

// --- 6. overtime hidden ------------------------------------------------------
t('show.otHours false: no overtime-hours and no regular-hours line', () => {
  const out = buildTimecardText(model({
    rows: [day('Mon', '09:00', '17:00', '')],
    show: { otHours: false, pay: false, otPay: false }
  }));
  assert.ok(!out.split('\n').some((l) => l.includes('Overtime hours')));
  assert.ok(!out.split('\n').some((l) => l.includes('Regular hours')));
});

// --- 7. pay hidden -----------------------------------------------------------
t('show.pay false: no rate line and no gross-pay line', () => {
  const out = buildTimecardText(model({
    rows: [day('Mon', '09:00', '17:00', '')],
    show: { otHours: false, pay: false, otPay: false },
    rate: 20
  }));
  assert.ok(!out.split('\n').some((l) => l.includes('USD')));
  assert.ok(!out.split('\n').some((l) => l.includes('gross pay')));
});

// --- 8. label sanitisation ---------------------------------------------------
t('label: tabs and newlines become single spaces, day line keeps 5 tabs', () => {
  const out = buildTimecardText(model({
    rows: [day('Night\tShift\nA', '09:00', '17:00', '')]
  }));
  const line = out.split('\n')[1];
  assert.equal(line.split('\t')[0], 'Night Shift A');
  assert.equal((line.match(/\t/g) || []).length, 5);
  // header + row + blank + 2 totals + blank + rounding + 3 footer lines.
  assert.equal(out.split('\n').length, 1 + 1 + 1 + 2 + 1 + 1 + 3); // no stray line breaks
});

// --- 9. zero rows ------------------------------------------------------------
t('zero rows: totals are a real 0.00 / 0:00, not blank', () => {
  const out = buildTimecardText(model({ rows: [] }));
  assert.ok(out.includes('Total hours (decimal)\t0.00'));
  assert.ok(out.includes('Total hours (h:mm)\t0:00'));
});

// --- 10. money formatting ----------------------------------------------------
t('money: 1250 exports 1250.00, no $, no comma, no trailing newline', () => {
  const out = buildTimecardText(model({
    rows: [day('Mon', '09:00', '17:00', '')],
    show: { otHours: false, pay: true, otPay: false },
    rate: 1250
  }));
  assert.ok(out.includes('Hourly rate (USD)\t1250.00'));
  assert.ok(!out.includes('$'));
  // No thousands separator in any money field. Scoped to the money values, not
  // the whole payload: the provenance sentence legitimately contains a comma.
  const moneyValues = out.split('\n')
    .filter((l) => /^(Hourly rate \(USD\)|Regular pay|Overtime pay |Estimated gross pay)/.test(l))
    .map((l) => l.split('\t')[1]);
  assert.ok(moneyValues.length > 0);
  moneyValues.forEach((v) => assert.ok(!v.includes(',') && !v.includes('$'), v));
  assert.ok(!out.endsWith('\n'));
});

// A line's value cell, looked up by its label. Returns undefined when absent.
const cell = (out, label) => {
  const line = out.split('\n').find((l) => l.split('\t')[0] === label);
  return line === undefined ? undefined : line.split('\t')[1];
};
// The label of the line that starts with `prefix`, e.g. the parenthesised rule.
const labelStartingWith = (out, prefix) =>
  out.split('\n').map((l) => l.split('\t')[0]).find((l) => l.startsWith(prefix));

// --- 11. the multiplier label names the multiplier that was applied ----------
t('multiplier: an out-of-range -2 prints as the 1.5 the engine really used', () => {
  const out = buildTimecardText(model({ ...GOLDEN_MODEL, otMult: -2 }));
  // 6 overtime hours at 20/h. 180.00 is 1.5x, so the label may not say -2x.
  assert.equal(cell(out, 'Overtime pay (1.5x rate)'), '180.00');
  assert.ok(!out.includes('-2x rate'));
  assert.equal(cell(out, 'Estimated gross pay'), '980.00');
  // 0 and blank fall back the same way, and a numeric string is rejected by
  // grossPayOvertime, so the label has to report 1.5 there too.
  assert.equal(effectiveMultiplier(0), 1.5);
  assert.equal(effectiveMultiplier(NaN), 1.5);
  assert.equal(effectiveMultiplier('2'), 1.5);
  assert.equal(effectiveMultiplier(2), 2);
});

// --- 12. the threshold label names the threshold that was applied -----------
t('threshold: an out-of-range -10 prints as the 40 the engine really used', () => {
  const out = buildTimecardText(model({ ...GOLDEN_MODEL, otThreshold: -10 }));
  assert.equal(cell(out, 'Regular hours (first 40 h/week)'), '40.00');
  assert.equal(cell(out, 'Overtime hours'), '6.00');
  assert.ok(!out.includes('-10 h/week'));
  assert.equal(effectiveThreshold(-10), 40);
  assert.equal(effectiveThreshold(NaN), 40);
  assert.equal(effectiveThreshold('35'), 35);
});

// --- 12b. a real 0 threshold is honoured, not swallowed by the fallback ------
t('threshold: a deliberate 0 stays 0, every hour is overtime and the label says so', () => {
  const out = buildTimecardText(model({
    rows: [day('Mon', '09:00', '17:00', '')],
    show: { otHours: true, pay: false, otPay: false },
    otOn: true,
    otThreshold: 0
  }));
  assert.equal(cell(out, 'Regular hours (first 0 h/week)'), '0.00');
  assert.equal(cell(out, 'Overtime hours'), '8.00');
  assert.equal(effectiveThreshold(0), 0);
});

// --- 13. the rate and the gross pay multiply out ----------------------------
t('rate: 20.555 over 10 h prints the rate that was multiplied, not a rounded one', () => {
  const out = buildTimecardText(model({
    rows: [day('Mon', '09:00', '19:00', '')],
    show: { otHours: false, pay: true, otPay: false },
    rate: 20.555
  }));
  assert.equal(cell(out, 'Hourly rate (USD)'), '20.555');
  assert.equal(cell(out, 'Estimated gross pay'), '205.55');
  // The reader's own arithmetic, on the printed figures only.
  const rate = Number(cell(out, 'Hourly rate (USD)'));
  const hours = Number(cell(out, 'Total hours (decimal)'));
  assert.equal((rate * hours).toFixed(2), cell(out, 'Estimated gross pay'));
});

// --- 14. sub-cent rates stay honest, whole rates keep their 2 decimals ------
t('rate: 0.005 prints 0.005 beside 0.05, and 20 still prints 20.00', () => {
  const tiny = buildTimecardText(model({
    rows: [day('Mon', '09:00', '19:00', '')],
    show: { otHours: false, pay: true, otPay: false },
    rate: 0.005
  }));
  assert.equal(cell(tiny, 'Hourly rate (USD)'), '0.005');
  assert.equal(cell(tiny, 'Estimated gross pay'), '0.05');
  assert.equal((0.005 * 10).toFixed(2), cell(tiny, 'Estimated gross pay'));

  const plain = buildTimecardText(model({
    rows: [day('Mon', '09:00', '19:00', '')],
    show: { otHours: false, pay: true, otPay: false },
    rate: 20
  }));
  assert.equal(cell(plain, 'Hourly rate (USD)'), '20.00');
  assert.equal(cell(plain, 'Estimated gross pay'), '200.00');

  const half = buildTimecardText(model({
    rows: [day('Mon', '09:00', '19:00', '')],
    show: { otHours: false, pay: true, otPay: false },
    rate: 20.5
  }));
  assert.equal(cell(half, 'Hourly rate (USD)'), '20.50');
  assert.equal(cell(half, 'Estimated gross pay'), '205.00');
});

// --- 15. the hours column that cannot add up says so ------------------------
t('rounding: five 25-minute days add to 2.10 under a 2.08 total, and the file names it', () => {
  const out = buildTimecardText(model({
    rows: [1, 2, 3, 4, 5].map((n) => day('D' + n, '09:00', '09:25', ''))
  }));
  const lines = out.split('\n');
  const decimals = lines.slice(1, 6).map((l) => l.split('\t')[4]);
  assert.deepEqual(decimals, ['0.42', '0.42', '0.42', '0.42', '0.42']);
  assert.equal(cell(out, 'Total hours (decimal)'), '2.08');
  assert.equal(cell(out, 'Total hours (h:mm)'), '2:05');
  // The column really does not reach the total, which is why the line exists.
  const summed = decimals.reduce((a, b) => a + Number(b), 0);
  assert.equal(summed.toFixed(2), '2.10');
  assert.notEqual(summed.toFixed(2), cell(out, 'Total hours (decimal)'));
  assert.ok(lines.includes(ROUND_HOURS), 'rounding statement missing');
  // The h:mm column, which the statement points at, does reconcile exactly.
  assert.equal(lines.slice(1, 6).every((l) => l.split('\t')[5] === '0:25'), true);
});

// --- 16. the same defect at a different shift length ------------------------
t('rounding: seven 1:07 days add to 7.84 under a 7.82 total, and the file names it', () => {
  const out = buildTimecardText(model({
    rows: [1, 2, 3, 4, 5, 6, 7].map((n) => day('D' + n, '09:00', '10:07', ''))
  }));
  const decimals = out.split('\n').slice(1, 8).map((l) => l.split('\t')[4]);
  assert.deepEqual(decimals, ['1.12', '1.12', '1.12', '1.12', '1.12', '1.12', '1.12']);
  assert.equal(cell(out, 'Total hours (decimal)'), '7.82');
  assert.equal(decimals.reduce((a, b) => a + Number(b), 0).toFixed(2), '7.84');
  assert.ok(out.split('\n').includes(ROUND_HOURS), 'rounding statement missing');
});

// --- 17. the rounding statement only claims what the file contains ----------
t('rounding: the pay clause appears only with pay, the hours clause only with rows', () => {
  const noPay = buildTimecardText(model({ rows: [day('Mon', '09:00', '17:00', '')] }));
  assert.ok(noPay.split('\n').includes(ROUND_HOURS));
  assert.ok(!noPay.includes(ROUND_PAY));

  const withPay = buildTimecardText(model({
    rows: [day('Mon', '09:00', '17:00', '')],
    show: { otHours: false, pay: true, otPay: false },
    rate: 20
  }));
  assert.ok(withPay.split('\n').includes(ROUND_HOURS + ' ' + ROUND_PAY));

  // No rows and no pay: nothing is rounded, so nothing is claimed.
  const empty = buildTimecardText(model({ rows: [] }));
  assert.ok(!empty.includes('rounded'));
  assert.ok(!empty.includes('2 decimals'));
  assert.equal(empty.split('\n').length, 1 + 1 + 2 + 1 + 3);
});

// --- 18. formula-looking day labels ------------------------------------------
t('label: a label opening with = + - or @ is neutralised for spreadsheets', () => {
  const out = buildTimecardText(model({
    rows: [
      day('=1+1', '09:00', '17:00', ''),
      day('-Monday', '09:00', '17:00', ''),
      day('+OT day', '09:00', '17:00', ''),
      day('@home', '09:00', '17:00', ''),
      day('  =SUM(A1:A9)  ', '09:00', '17:00', ''),
      day('Monday', '09:00', '17:00', '')
    ]
  }));
  const labels = out.split('\n').slice(1, 7).map((l) => l.split('\t')[0]);
  assert.deepEqual(labels, [
    ' =1+1', ' -Monday', ' +OT day', ' @home', ' =SUM(A1:A9)', 'Monday'
  ]);
  // A live formula would have pasted as a value the visitor never typed.
  assert.ok(!out.split('\n').some((l) => l.startsWith('=')));
  // One space only, and the row shape is untouched.
  assert.ok(!labels.some((l) => l.startsWith('  ')));
  out.split('\n').slice(1, 7).forEach((l) =>
    assert.equal((l.match(/\t/g) || []).length, 5));
  // Ordinary labels, and the empty label, are passed through byte for byte.
  const plain = buildTimecardText(model({ rows: [day('', '09:00', '17:00', '')] }));
  assert.equal(plain.split('\n')[1].split('\t')[0], '');
});

// --- 19. the overtime rule label survives a full round trip ------------------
t('label + figure: a 2x multiplier at a 35 h threshold is described by its own numbers', () => {
  const out = buildTimecardText(model({
    ...GOLDEN_MODEL,
    otThreshold: 35,
    otMult: 2
  }));
  assert.equal(cell(out, 'Regular hours (first 35 h/week)'), '35.00');
  assert.equal(cell(out, 'Overtime hours'), '11.00');
  assert.equal(labelStartingWith(out, 'Overtime pay'), 'Overtime pay (2x rate)');
  assert.equal(cell(out, 'Regular pay'), '700.00');           // 35 x 20
  assert.equal(cell(out, 'Overtime pay (2x rate)'), '440.00'); // 11 x 20 x 2
  assert.equal(cell(out, 'Estimated gross pay'), '1140.00');
});

